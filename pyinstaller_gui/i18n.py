STRINGS = {"es": {k: v[0] for k, v in _TEXTS.items()},
           "en": {k: v[1] for k, v in _TEXTS.items()}}


def tr(key: str, **kwargs) -> str:
    """Texto traducido. Si falta en el idioma activo usa español; si falta en ambos,
    muestra la clave (así se nota enseguida en pantalla)."""
    text = STRINGS.get(LANG, {}).get(key) or STRINGS["es"].get(key) or key
    return text.format(**kwargs) if kwargs else text


def tr_opt(key: str) -> str:
    """Como tr(), pero devuelve '' si la clave no existe (para textos opcionales)."""
    return STRINGS.get(LANG, {}).get(key) or STRINGS["es"].get(key) or ""


def check_translations() -> list:
    """Solo en desarrollo: claves vacías en algún idioma (con el formato de tuplas no
    puede faltar una clave, pero sí quedar un texto vacío)."""
    problems = []
    for key, pair in _TEXTS.items():
        for code, text in zip(LANGUAGES, pair):
            if not text:
                problems.append(f"[i18n] '{key}' vacío en '{code}'")
    return problems
